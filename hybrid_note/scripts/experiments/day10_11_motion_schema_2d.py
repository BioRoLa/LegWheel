"""Day 10--11 Step 6: the segment-level motion sequence schema.

Spec 5.4, and the gap 2.5 opened.  The original plan's output contract asked
for ``target contact / rim / alpha / foothold for every transition``, and three
things do not fit in it:

* a **wheel-mode segment has no fixed contact point** -- the leg rolls at
  ``theta = 17 deg`` and the contact walks along the rim, so one rim plus one
  alpha cannot describe it;
* a **swing carries planner-internal shaping** -- ``liftoff_rise``,
  ``touchdown_drop``, ``swing_duration``, ``apex clearance`` -- that no contact
  state mentions;
* **sampling density is part of the case, not a free knob**: Day 8--9 Step 9
  found ``max_joint_step_rad`` is a per-sample limit, so the same trajectory
  sampled twice as densely has half the step.  A sequence that does not record
  its sampling is not reproducible.

So the schema is per **segment**, and each segment carries its own sampling and
its own body requirement.

Two things the data forced that spec 5.4 did not anticipate
-----------------------------------------------------------

**1. ``alpha_range`` is not enough to describe a rolling segment.**
Day 6--7 Step 10R's ``LEFT_RIM_TRAILING_TRANSITION`` and
``LEFT_RIM_ROLL_DOWN`` hold ``alpha`` at ``-134.5 deg`` and the contact point
at the trailing corner ``(450.0, 100.0) mm`` for **72 frames**, while ``beta``
sweeps 71 degrees.  The leg is not rolling; it is **pivoting about one point on
the rim**.  A schema that records only the alpha range describes those frames
as a single static pose.  :class:`RollingContact2D` therefore records the beta
range as well, and :class:`RollingMode` names which of the two is happening.

**2. Rolling and swing do not share a sampling vocabulary.**
A swing is sampled in time (``sample_count``) and checked against a per-sample
joint step; a rolling stage is stepped in ``beta`` (and, during a retract, in
``theta``) until a stop condition fires.  One struct with half its fields
``None`` would make "which fields are required" unanswerable, which is exactly
what the completion criterion tests.  So there are two sampling types, and each
is complete for its own family.

**What this module does not invent.**  Day 6--7's traversal is quasi-static and
was never assigned time, so ``duration_s`` is ``None`` on every segment built
from it.  Making one up would put a fabricated number where a real one has to
go later; Step 7 or Day 12 must supply it.
"""

