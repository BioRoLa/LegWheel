@dataclass(frozen=True)
class MotionSegment2D:
    """One motion, with everything needed to regenerate and to price it."""

    kind: SegmentKind
    start_contact: SegmentEndpoint2D
    end_contact: SegmentEndpoint2D
    sampling: SamplingSpec2D
    body_requirement: BodyRequirement2D
    frames: FrameRef2D
    #: ``None`` where the source never assigned time.  Day 6--7's traversal is
    #: quasi-static, so every rolling segment built from it has no duration --
    #: recorded as missing rather than invented.
    duration_s: float | None = None
    #: The phase label the source used, kept so a segment can be traced back.
    phase_label: str = ""
    #: Cartesian-swing-only (``SWING_UP`` / ``SWING_DOWN`` / ``SWING_OVER``).
    swing_shaping: SwingShaping2D | None = None
    #: ``RECOVERY_SWING``-only: its own knobs, not Day 8--9's.
    recovery_shaping: RecoveryShaping2D | None = None
    #: Rolling-only: what actually moved.
    rolling: RollingContact2D | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "kind", SegmentKind(self.kind))
        if self.kind is SegmentKind.RECOVERY_SWING:
            # A recovery is airborne, but it is generated the way a rolling
            # stage is -- stepped in theta and beta until a condition fires --
            # so it takes RollSampling2D, not Day 8--9's time-sampled spec.
            if not isinstance(self.sampling, RollSampling2D):
                raise TypeError(
                    "a RECOVERY_SWING is stepped in theta/beta, so it needs "
                    "RollSampling2D; SwingSampling2D describes a Cartesian "
                    "swing sampled in time."
                )
            if self.recovery_shaping is None:
                raise ValueError(
                    "a RECOVERY_SWING must record its own shaping "
                    "(theta_compact / theta_touchdown / airborne rotation / "
                    "clearance); Day 8--9's swing knobs do not describe it."
                )
            if self.swing_shaping is not None:
                raise ValueError(
                    "a RECOVERY_SWING is not a Cartesian swing; it must not "
                    "carry SwingShaping2D."
                )
            if not isinstance(self.start_contact, PointContact2D):
                raise TypeError("a recovery leaves from one definite contact point.")
        elif self.kind.is_swing:
            if not isinstance(self.sampling, SwingSampling2D):
                raise TypeError("a swing segment needs SwingSampling2D.")
            if self.swing_shaping is None:
                raise ValueError(
                    "a swing segment must record its shaping knobs "
                    "(liftoff_rise / touchdown_drop / clearance / duration): "
                    "spec 2.5's second gap."
                )
            if not isinstance(self.start_contact, PointContact2D):
                raise TypeError("a swing leaves from one definite contact point.")
        else:
            if not isinstance(self.sampling, RollSampling2D):
                raise TypeError("a rolling segment needs RollSampling2D.")
            if self.rolling is None:
                raise ValueError(
                    "a rolling segment must record what moved during it "
                    "(alpha range, beta range, mode): spec 2.5's first gap."
                )
            self._check_day12_rolling_semantics()
        if self.duration_s is not None and (
            not np.isfinite(self.duration_s) or self.duration_s <= 0.0
        ):
            raise ValueError("duration_s must be positive when given.")

    def _check_day12_rolling_semantics(self) -> None:
        """Enforce what the two Day 12 rolling names actually claim.

        An enum member with no enforced meaning is the failure mode the Day
        10--11 log names again and again: a label built for one situation gets
        applied to another and produces a conclusion nobody argued for.  So
        each of the two names is checked against the one thing it asserts, and
        against nothing else.

        ``FOOT_RIM_ROLL``
            asserts the **foot rim** is the rolling contact.  It asserts
            nothing about ``theta`` -- being free of wheel mode is the whole
            point, so a theta check here would re-impose what the kind exists
            to remove.

        ``WHEEL_ROLL``
            asserts ``theta`` is wheel mode, over the whole segment.  It
            asserts nothing about which rim carries the contact, because at
            ``theta = 17 deg`` that is the geometry's business, not the label's.
        """

        rolling = self.rolling
        assert rolling is not None  # the caller checked
        if self.kind is SegmentKind.FOOT_RIM_ROLL and rolling.rim is not RimId.FOOT:
            raise ValueError(
                "FOOT_RIM_ROLL asserts the foot rim is the rolling contact; "
                f"this segment rolls on {rolling.rim.value}.  Use "
                "POST_TOUCHDOWN_ROLL for rolling on whichever rim a swing "
                "landed on."
            )
        if self.kind.pins_theta:
            low, high = rolling.theta_range_rad
            off = max(
                abs(low - WHEEL_MODE_THETA_RAD), abs(high - WHEEL_MODE_THETA_RAD)
            )
            if off > WHEEL_MODE_THETA_TOLERANCE_RAD:
                raise ValueError(
                    f"WHEEL_ROLL means true wheel mode "
                    f"(theta = {np.rad2deg(WHEEL_MODE_THETA_RAD):.0f} deg), but "
                    f"this segment holds theta in "
                    f"[{np.rad2deg(low):.1f}, {np.rad2deg(high):.1f}] deg.  An "
                    "expanded-posture flat run is FOOT_RIM_ROLL, not WHEEL_ROLL."
                )

    def as_dict(self) -> dict:
        row = {
            "kind": self.kind.value,
            "phase_label": self.phase_label,
            "pins_theta": self.kind.pins_theta,
            "is_nominal_locomotion": self.kind.is_nominal_locomotion,
            "is_terrain_transition": self.kind.is_terrain_transition,
            "duration_s": self.duration_s,
            "frame_source": self.frames.source_id,
            "frame_count": self.frames.frame_count,
            "frame_from": self.frames.indices[0],
            "frame_to": self.frames.indices[-1],
            "frames_contiguous": self.frames.is_contiguous,
        }
        row.update(self.sampling.as_dict())
        row.update(self.body_requirement.as_dict())
        if self.rolling is not None:
            row.update(self.rolling.as_dict())
        if self.swing_shaping is not None:
            row.update(self.swing_shaping.as_dict())
        if self.recovery_shaping is not None:
            row.update(self.recovery_shaping.as_dict())
        return row


class TransitionKind(str, Enum):
    """A transition a sequence needs but this project cannot yet generate."""

    #: Spec 5.6.  After crossing onto the obstacle top, a real quadruped does
    #: not have to continue from the same contact: while other legs carry the
    #: body, this one can lift off again, re-choose ``theta`` / ``beta`` and a
    #: landing point mid-air, and come down in a pose that suits the next
    #: segment.  A single-leg 2D model cannot generate it, because it cannot
    #: answer who is holding the body up meanwhile.
    TOP_REPOSITION = "TOP_REPOSITION"


@dataclass(frozen=True)
class TransitionRequirement2D:
    """Something the sequence needs, recorded **without** inventing it.

    Spec 5.6.  This exists so a hand-off file can tell three things apart:

    ``a segment``            a motion that was generated and checked
    ``a requirement``        a motion that is needed and is **not yet solved**
    ``nothing``             the case where no such motion is needed at all

    Without the middle one, Step 9's deliverable collapses "unsolved" into
    "absent", which is exactly the over-generalisation spec 5.5 exists to stop.

    **It carries no trajectory and no duration.**  Generating one here would
    tacitly assume body support that no single-leg planner can validate, and
    that assumption would then be read as a result.
    """

    kind: TransitionKind
    #: The contact the leg leaves from.
    source_contact: PointContact2D
    #: What the next segment needs on entry, in words -- ``LEFT_RIM_READY``,
    #: "a foot-rim take-off above theta = 35 deg", and so on.  Deliberately not
    #: a pose: pinning one down is the work this record is deferring.
    target_condition: str
    #: Why the direct hand-over does not work, pointing at the measurement.
    evidence: str
    #: True whenever another leg has to carry the body for this to happen.
    requires_external_support: bool = True
    #: Always ``False`` here.  A later stage that generates the motion is what
    #: flips it, and it should replace the record with a real segment.
    resolved: bool = False

    def __post_init__(self) -> None:
        object.__setattr__(self, "kind", TransitionKind(self.kind))
        if not isinstance(self.source_contact, PointContact2D):
            raise TypeError("source_contact must be a PointContact2D.")
        for name in ("target_condition", "evidence"):
            if not str(getattr(self, name)).strip():
                raise ValueError(f"{name} must not be empty.")
        if self.resolved:
            raise ValueError(
                "a resolved transition is a segment, not a requirement: replace "
                "the record with the motion that solves it."
            )

    def as_dict(self) -> dict:
        return {
            "transition_kind": self.kind.value,
            "target_condition": self.target_condition,
            "requires_external_support": self.requires_external_support,
            "resolved": self.resolved,
            "evidence": self.evidence,
            **{f"from_{k}": v for k, v in self.source_contact.as_dict().items()},
        }


@dataclass(frozen=True)
class MotionSequence2D:
    """An ordered chain of segments over one terrain."""

    terrain_id: str
    segments: tuple[MotionSegment2D, ...]
    #: Transitions the sequence needs and that nothing here can generate yet
    #: (spec 5.6).  A sequence with any of these is **not** a complete plan;
    #: :attr:`is_complete` is what says so.
    unresolved: tuple[TransitionRequirement2D, ...] = ()
    notes: str = ""

    def __post_init__(self) -> None:
        if not self.terrain_id:
            raise ValueError("terrain_id must not be empty.")
        segments = tuple(self.segments)
        if not segments:
            raise ValueError("a sequence has at least one segment.")
        sources = {s.frames.source_id for s in segments}
        if len(sources) != 1:
            raise ValueError(
                "every segment of one sequence must reference the same frame "
                f"source; got {sorted(sources)}."
            )
        seen: set[int] = set()
        for segment in segments:
            overlap = seen & set(segment.frames.indices)
            if overlap:
                raise ValueError(
                    f"segments overlap on frames {sorted(overlap)[:5]}: a frame "
                    "belongs to exactly one segment."
                )
            seen |= set(segment.frames.indices)
        object.__setattr__(self, "segments", segments)
        object.__setattr__(self, "unresolved", tuple(self.unresolved))

    @property
    def is_complete(self) -> bool:
        """Whether this is a plan, or a plan with a hole in it.

        A caller that reads only ``segments`` would treat a sequence carrying
        an unresolved requirement as executable.  It is not.
        """

        return not self.unresolved

    @property
    def frame_indices(self) -> tuple[int, ...]:
        return tuple(sorted(i for s in self.segments for i in s.frames.indices))

    @property
    def total_duration_s(self) -> float | None:
        """``None`` if any segment has no time -- a partial sum would mislead."""

        if any(s.duration_s is None for s in self.segments):
            return None
        return float(sum(s.duration_s for s in self.segments))

    def rows(self) -> list[dict]:
        """Segments and unresolved requirements in one table.

        They share a table on purpose: a hand-off file that listed only the
        segments would read as complete.  ``row_kind`` keeps them apart.
        """

        rows = [
            {"terrain_id": self.terrain_id, "row_kind": "segment",
             "segment_index": i, **s.as_dict()}
            for i, s in enumerate(self.segments)
        ]
        rows += [
            {"terrain_id": self.terrain_id, "row_kind": "unresolved_transition",
             "segment_index": len(self.segments) + i, **t.as_dict()}
            for i, t in enumerate(self.unresolved)
        ]
        return rows
