@dataclass(frozen=True)
class BodyRequirement2D:
    """What this segment asks of the body trajectory, over its own x range.

    ``kind`` is Step 1's :class:`BodyRequirementKind`, not a second enum: the
    whole point of Day 10--11 is that a planner *outputs* one of these, and a
    sequence that used different names from the concessions would break the
    link between Step 5's decision and Step 9's timeline.
    """

    kind: BodyRequirementKind
    x_range_m: tuple[float, float]
    hip_z_min_m: float | None = None
    hip_z_profile_m: NDArray[np.float64] | None = None

    def __post_init__(self) -> None:
        object.__setattr__(self, "kind", BodyRequirementKind(self.kind))
        low, high = (float(v) for v in self.x_range_m)
        if high < low:
            raise ValueError("x_range_m must be ordered (low, high).")
        object.__setattr__(self, "x_range_m", (low, high))
        if self.hip_z_profile_m is not None:
            profile = np.asarray(self.hip_z_profile_m, dtype=float).reshape(-1)
            # One sample is legitimate.  Day 6--7 Step 10R's
            # ``RIGHT_RIM_FRONT_CONTACT`` is a single frame -- the instant the
            # wheel first touches the front face -- and it is a phase the
            # traversal named itself.  Refusing it would force the builder to
            # merge that frame into a neighbour, which is exactly the loss this
            # step is supposed to avoid.
            if profile.size < 1:
                raise ValueError("a hip_z profile needs at least one sample.")
            if not np.all(np.isfinite(profile)):
                raise ValueError("hip_z_profile_m must be finite.")
            profile.setflags(write=False)
            object.__setattr__(self, "hip_z_profile_m", profile)
        if self.kind is BodyRequirementKind.TRACK and self.hip_z_profile_m is None:
            raise ValueError(
                "a TRACK requirement is a trajectory; it needs hip_z_profile_m."
            )
        if (
            self.kind in (BodyRequirementKind.LOWER_BOUND, BodyRequirementKind.PINNED)
            and self.hip_z_min_m is None
        ):
            raise ValueError(
                f"a {self.kind.value} requirement is a height; it needs hip_z_min_m."
            )

    @property
    def hip_z_travel_m(self) -> float | None:
        if self.hip_z_profile_m is None:
            return None
        return float(self.hip_z_profile_m.max() - self.hip_z_profile_m.min())

    def as_dict(self) -> dict:
        return {
            "body_kind": self.kind.value,
            "x_from_mm": self.x_range_m[0] * 1e3,
            "x_to_mm": self.x_range_m[1] * 1e3,
            "hip_z_min_mm": (
                None if self.hip_z_min_m is None else self.hip_z_min_m * 1e3
            ),
            "hip_z_travel_mm": (
                None if self.hip_z_travel_m is None else self.hip_z_travel_m * 1e3
            ),
            "profile_samples": (
                0 if self.hip_z_profile_m is None else int(self.hip_z_profile_m.size)
            ),
        }


# --------------------------------------------------------------------------
# Frames, by reference
# --------------------------------------------------------------------------


@dataclass(frozen=True)
class FrameRef2D:
    """Where this segment's per-frame data lives.  Spec 5.4: **not embedded**.

    ``indices`` is the explicit list rather than a range, because Step 10R's
    own output is not contiguous -- index 11 is missing, a frame the traversal
    proposed and rejected.  A ``(start, stop)`` pair would silently claim it.
    """

    source_id: str
    indices: tuple[int, ...]

    def __post_init__(self) -> None:
        if not self.source_id:
            raise ValueError("source_id must not be empty.")
        indices = tuple(int(i) for i in self.indices)
        if not indices:
            raise ValueError("a segment references at least one frame.")
        if list(indices) != sorted(indices):
            raise ValueError("frame indices must be ascending.")
        if len(set(indices)) != len(indices):
            raise ValueError("frame indices must be unique.")
        object.__setattr__(self, "indices", indices)

    @property
    def frame_count(self) -> int:
        return len(self.indices)

    @property
    def is_contiguous(self) -> bool:
        return self.indices[-1] - self.indices[0] + 1 == len(self.indices)


