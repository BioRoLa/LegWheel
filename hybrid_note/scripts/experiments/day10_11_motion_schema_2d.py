@dataclass(frozen=True)
class RollSampling2D:
    """What it takes to regenerate a rolling stage.  **No defaults.**

    ``beta_step_rad`` is the nominal increment; a stage that stops on an event
    truncates its last step, and the exact sequence lives in the referenced
    frames rather than being re-derivable from this.  ``theta_step_rad`` is
    ``None`` unless the stage is a coupled retract, where theta and beta move
    together (Step 10R's ``RETRACT_TO_WHEEL`` steps both by 1 degree).
    """

    arc_samples: int
    beta_step_rad: float
    theta_step_rad: float | None

    def __post_init__(self) -> None:
        if self.arc_samples < 3:
            raise ValueError("arc_samples must be at least 3.")
        if not np.isfinite(self.beta_step_rad) or self.beta_step_rad == 0.0:
            raise ValueError("beta_step_rad must be finite and non-zero.")
        if self.theta_step_rad is not None and not np.isfinite(self.theta_step_rad):
            raise ValueError("theta_step_rad must be finite when given.")

    def as_dict(self) -> dict:
        return {
            "arc_samples": self.arc_samples,
            "beta_step_deg": float(np.rad2deg(self.beta_step_rad)),
            "theta_step_deg": (
                None if self.theta_step_rad is None
                else float(np.rad2deg(self.theta_step_rad))
            ),
        }


@dataclass(frozen=True)
class SwingSampling2D:
    """What it takes to regenerate a swing.  **No defaults.**

    Spec 5.4's four fields.  Every one is load-bearing:

    ``arc_samples``
        the terrain contact query's rim resolution.  Day 6--7 trap 2: the seam
        width is a sampling artefact and a low value falsely rejects a rim
        hand-over.
    ``sample_count``
        how many samples the trajectory is cut into.
    ``leg_arc_samples``
        the resolution the collision check sweeps the leg at.
    ``max_joint_step_rad``
        a **per-sample** limit (Day 8--9 Step 9), so it is coupled to
        ``sample_count``: the same trajectory sampled twice as densely has half
        the step.  Recording one without the other decides nothing.
    """

    arc_samples: int
    sample_count: int
    leg_arc_samples: int
    max_joint_step_rad: float

    def __post_init__(self) -> None:
        for name in ("arc_samples", "sample_count", "leg_arc_samples"):
            if getattr(self, name) < 3:
                raise ValueError(f"{name} must be at least 3.")
        if not np.isfinite(self.max_joint_step_rad) or self.max_joint_step_rad <= 0.0:
            raise ValueError("max_joint_step_rad must be finite and positive.")

    @property
    def implied_joint_speed_limit_rad(self) -> float:
        """The sampling-independent view of the joint limit.

        ``max_joint_step`` times ``sample_count`` is what actually bounds the
        motion; two segments with the same product describe the same limit.
        """

        return float(self.max_joint_step_rad * (self.sample_count - 1))

    def as_dict(self) -> dict:
        return {
            "arc_samples": self.arc_samples,
            "sample_count": self.sample_count,
            "leg_arc_samples": self.leg_arc_samples,
            "max_joint_step_deg": float(np.rad2deg(self.max_joint_step_rad)),
        }


SamplingSpec2D = RollSampling2D | SwingSampling2D


@dataclass(frozen=True)
class SwingShaping2D:
    """The planner-internal knobs spec 2.5 says no contact state mentions."""

    apex_clearance_m: float
    liftoff_rise_m: float
    touchdown_drop_m: float
    duration_scale: float
    mid_fractions: tuple[float, float]

    def __post_init__(self) -> None:
        for name in ("apex_clearance_m", "liftoff_rise_m", "touchdown_drop_m",
                     "duration_scale"):
            value = float(getattr(self, name))
            if not np.isfinite(value):
                raise ValueError(f"{name} must be finite.")
            object.__setattr__(self, name, value)
        if self.duration_scale <= 0.0:
            raise ValueError("duration_scale must be positive.")
        object.__setattr__(
            self, "mid_fractions", tuple(float(v) for v in self.mid_fractions)
        )

    def as_dict(self) -> dict:
        return {
            "apex_clearance_mm": self.apex_clearance_m * 1e3,
            "liftoff_rise_mm": self.liftoff_rise_m * 1e3,
            "touchdown_drop_mm": self.touchdown_drop_m * 1e3,
            "duration_scale": self.duration_scale,
        }


@dataclass(frozen=True)
class RecoveryShaping2D:
    """What generated a ``RECOVERY_SWING``.  Day 12, and a third family.

    :class:`SwingShaping2D` records the knobs a **Cartesian** swing is shaped
    by -- apex clearance, liftoff rise, touchdown drop, duration scale.  A
    nominal recovery has none of them: it is not a contact-point path at all,
    but a joint-space move -- retract to a compact posture, carry the rotation
    on forward, extend into the next touchdown.  Filling Day 8--9's fields with
    zeros would put invented numbers exactly where real ones belong, which is
    the failure this schema's two sampling families already exist to prevent.

    So a recovery records **its own** knobs, and
    :class:`MotionSegment2D` asks for this instead of ``swing_shaping`` when
    the kind is ``RECOVERY_SWING``.
    """

    #: The compact posture the leg retracts to.  Day 12 MVP sets it to wheel
    #: mode, but it is a *recovery parameter* that happens to coincide -- not
    #: the same quantity as ``WHEEL_MODE_THETA_RAD``, which is what
    #: ``WHEEL_ROLL`` means.  Plan section 0.2 is explicit that 17 deg must not
    #: harden into a constant scattered through the planner.
    theta_compact_rad: float
    #: The posture the next touchdown contact requires.  Plan section 8.4: it
    #: is decided by the next ``ContactState`` and terrain, and is **not**
    #: fixed to the compact value.
    theta_touchdown_rad: float
    #: How far the leg-wheel turns while airborne, in the same forward sense
    #: the rolling stroke used.
    airborne_rotation_rad: float
    #: Smallest gap between any sampled leg point and the terrain during the
    #: airborne phase.  The recovery's analogue of an apex clearance, measured
    #: rather than requested.
    min_clearance_m: float
    #: How far the hip advanced while airborne.  Zero means the body was not
    #: modelled as moving during recovery, which is Step 1's default because
    #: the body trajectory is Step 5's business.
    hip_advance_m: float

    def __post_init__(self) -> None:
        for name in ("theta_compact_rad", "theta_touchdown_rad",
                     "airborne_rotation_rad", "min_clearance_m", "hip_advance_m"):
            value = float(getattr(self, name))
            if not np.isfinite(value):
                raise ValueError(f"{name} must be finite.")
            object.__setattr__(self, name, value)
        if self.airborne_rotation_rad == 0.0:
            raise ValueError(
                "a recovery that does not rotate is not a recovery: the leg "
                "would land on the arc position it just left."
            )

    def as_dict(self) -> dict:
        return {
            "theta_compact_deg": float(np.rad2deg(self.theta_compact_rad)),
            "theta_touchdown_deg": float(np.rad2deg(self.theta_touchdown_rad)),
            "airborne_rotation_deg": float(np.rad2deg(self.airborne_rotation_rad)),
            "min_clearance_mm": self.min_clearance_m * 1e3,
            "recovery_hip_advance_mm": self.hip_advance_m * 1e3,
        }


