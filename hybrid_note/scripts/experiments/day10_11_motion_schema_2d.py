@dataclass(frozen=True)
class PointContact2D:
    """A contact at one definite point, with the leg configuration realising it.

    The Day 1 ``ContactState`` carries only the world contact data.  A segment
    endpoint additionally needs ``theta`` / ``beta`` / the hip, because Step 7's
    continuity check compares joint values across a hand-over and a contact
    match alone would pass a leg that flipped configuration.
    """

    rim: RimId
    alpha_rad: float
    point_world_xz_m: NDArray[np.float64]
    surface_id: str
    theta_rad: float
    beta_rad: float
    hip_xz_m: NDArray[np.float64]

    def __post_init__(self) -> None:
        object.__setattr__(self, "rim", RimId(self.rim))
        for name in ("point_world_xz_m", "hip_xz_m"):
            value = np.asarray(getattr(self, name), dtype=float).reshape(2)
            if not np.all(np.isfinite(value)):
                raise ValueError(f"{name} must be finite.")
            value.setflags(write=False)
            object.__setattr__(self, name, value)
        for name in ("alpha_rad", "theta_rad", "beta_rad"):
            value = float(getattr(self, name))
            if not np.isfinite(value):
                raise ValueError(f"{name} must be finite.")
            object.__setattr__(self, name, value)
        if not self.surface_id:
            raise ValueError("surface_id must not be empty.")

    def as_dict(self) -> dict:
        return {
            "rim": self.rim.value,
            "alpha_deg": float(np.rad2deg(self.alpha_rad)),
            "point_x_mm": float(self.point_world_xz_m[0]) * 1e3,
            "point_z_mm": float(self.point_world_xz_m[1]) * 1e3,
            "surface_id": self.surface_id,
            "theta_deg": float(np.rad2deg(self.theta_rad)),
            "beta_deg": float(np.rad2deg(self.beta_rad)),
            "hip_x_mm": float(self.hip_xz_m[0]) * 1e3,
            "hip_z_mm": float(self.hip_xz_m[1]) * 1e3,
        }


@dataclass(frozen=True)
class RollingContact2D:
    """A contact that moves during the segment.  Spec 2.5's missing case.

    ``alpha_range_rad`` is what spec 5.4 asked for.  ``beta_range_rad`` is what
    the data added: during a corner pivot the alpha range is a single point and
    only beta moves, so a schema without it records 72 frames of motion as a
    static pose.
    """

    rim: RimId
    surface_ids: tuple[str, ...]
    alpha_range_rad: tuple[float, float]
    beta_range_rad: tuple[float, float]
    theta_range_rad: tuple[float, float]
    contact_start_xz_m: NDArray[np.float64]
    contact_end_xz_m: NDArray[np.float64]

    #: How close two alphas have to be to count as pinned.  A tenth of a degree
    #: is far below the 1 degree beta step Step 10R actually uses, so a real
    #: roll never falls under it.
    ALPHA_PINNED_TOLERANCE_RAD = float(np.deg2rad(0.1))

    def __post_init__(self) -> None:
        object.__setattr__(self, "rim", RimId(self.rim))
        if not self.surface_ids:
            raise ValueError("a rolling contact touches at least one surface.")
        object.__setattr__(self, "surface_ids", tuple(self.surface_ids))
        for name in ("alpha_range_rad", "beta_range_rad", "theta_range_rad"):
            low, high = (float(v) for v in getattr(self, name))
            if not (np.isfinite(low) and np.isfinite(high)):
                raise ValueError(f"{name} must be finite.")
            if high < low:
                raise ValueError(f"{name} must be ordered (low, high).")
            object.__setattr__(self, name, (low, high))
        for name in ("contact_start_xz_m", "contact_end_xz_m"):
            value = np.asarray(getattr(self, name), dtype=float).reshape(2)
            value.setflags(write=False)
            object.__setattr__(self, name, value)

    @property
    def mode(self) -> RollingMode:
        """Which coordinate moved.

        A **single-frame** segment has a degenerate alpha range by
        construction, so it reports ``CORNER_PIVOT`` without having pivoted.
        :attr:`is_static` is the discriminator: a real pivot sweeps beta, a
        single frame sweeps nothing.  Day 6--7 Step 10R has one such segment
        (``RIGHT_RIM_FRONT_CONTACT``, the instant the wheel meets the face).
        """

        span = self.alpha_range_rad[1] - self.alpha_range_rad[0]
        if span <= self.ALPHA_PINNED_TOLERANCE_RAD:
            return RollingMode.CORNER_PIVOT
        return RollingMode.SURFACE_ROLL

    @property
    def beta_sweep_rad(self) -> float:
        return float(self.beta_range_rad[1] - self.beta_range_rad[0])

    @property
    def is_static(self) -> bool:
        """Nothing moves at all -- which no real segment should be.

        A pivot has a pinned alpha *and* a swept beta; if beta is pinned too,
        the segment is a single pose and something upstream mis-sliced it.
        """

        return (
            self.mode is RollingMode.CORNER_PIVOT
            and abs(self.beta_sweep_rad) <= self.ALPHA_PINNED_TOLERANCE_RAD
        )

    def as_dict(self) -> dict:
        return {
            "rim": self.rim.value,
            "mode": self.mode.value,
            # True only when neither alpha nor beta moved, which for a real
            # segment means it holds a single frame.
            "is_static": self.is_static,
            "surface_ids": ", ".join(self.surface_ids),
            "alpha_from_deg": float(np.rad2deg(self.alpha_range_rad[0])),
            "alpha_to_deg": float(np.rad2deg(self.alpha_range_rad[1])),
            "beta_sweep_deg": float(np.rad2deg(self.beta_sweep_rad)),
            "theta_from_deg": float(np.rad2deg(self.theta_range_rad[0])),
            "theta_to_deg": float(np.rad2deg(self.theta_range_rad[1])),
            "contact_start_x_mm": float(self.contact_start_xz_m[0]) * 1e3,
            "contact_end_x_mm": float(self.contact_end_xz_m[0]) * 1e3,
        }


SegmentEndpoint2D = PointContact2D | RollingContact2D


