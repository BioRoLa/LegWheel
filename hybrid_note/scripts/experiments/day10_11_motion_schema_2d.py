#: Wheel mode's theta, taken from the project's own configuration rather than
#: written down here.  Day 12 needs it as a **discriminator**, not as a target:
#: it is what ``WHEEL_ROLL`` means and what ``FOOT_RIM_ROLL`` is defined not to
#: require.
WHEEL_MODE_THETA_RAD = float(np.deg2rad(RobotParams.THETA0_DEG))

#: How far a ``WHEEL_ROLL`` segment's theta may sit from wheel mode and still
#: be one.  A degree is well above the retract step Day 6--7 uses (1 deg) and
#: far below the gap to any expanded posture (the nominal approach stands at
#: 60 deg), so it separates the two families without being brittle.
WHEEL_MODE_THETA_TOLERANCE_RAD = float(np.deg2rad(1.0))


class SegmentKind(str, Enum):
    """Every motion a sequence can contain.

    The seven of spec 5.4, plus the two the research plan's 10.5.4 requires the
    schema to be able to express even though Day 10--11 does not generate them:
    a long path spends most of its distance in ``WHEEL_ROLL``, and a swing that
    lands mid-obstacle continues in ``POST_TOUCHDOWN_ROLL``.  Adding them later
    would mean rewriting every consumer.
    """

    APPROACH = "APPROACH"
    ROLL_UP = "ROLL_UP"
    WHEEL_TRANSITION = "WHEEL_TRANSITION"
    ROLL_DOWN = "ROLL_DOWN"
    SWING_UP = "SWING_UP"
    SWING_DOWN = "SWING_DOWN"
    SWING_OVER = "SWING_OVER"
    #: Day 12 Step 7: the airborne relocation **on top of the obstacle** that
    #: Day 10--11 recorded as an unresolved ``TOP_REPOSITION``.  It exists as
    #: its own kind because it is neither of the two things it would otherwise
    #: be folded into: it is not ``SWING_OVER`` (which crosses the whole
    #: obstacle in one primitive), and it is not a ``RECOVERY_SWING`` (which is
    #: nominal locomotion the gait always makes).  It is a terrain-transition
    #: swing that only exists because two primitives would not chain directly,
    #: and plan §18's metrics count terrain-transition swings separately.
    #:
    #: It is generated by the **same** Day 8--9 swing planner as every other
    #: swing here -- plan §14 forbids a second reposition trajectory generator
    #: -- so this member names *when* the motion happens, not *how* it is made.
    TOP_REPOSITION_SWING = "TOP_REPOSITION_SWING"
    #: Flat-ground or flat-top propulsion at ``theta = 17 deg`` -- true wheel
    #: mode.  Zero hip concession; its cost is distance and time, not body
    #: deviation.  **Not** the proposed Hybrid gait's nominal locomotion: see
    #: :attr:`FOOT_RIM_ROLL`.
    WHEEL_ROLL = "WHEEL_ROLL"
    #: Day 12: the **rolling stance** half of the nominal Hybrid cycle.  The
    #: leg stays in its expanded posture -- ``theta`` is whatever the nominal
    #: configuration is, *not* 17 deg -- the foot rim stays in terrain contact,
    #: and the body advances by rolling the contact along the usable arc.  No
    #: obstacle in sight.
    #:
    #: **It is a finite stroke, not an indefinite one.**  The Day 12 plan's
    #: 2026-09-01 FINAL FREEZE (§0.2) explicitly retracted the earlier reading
    #: that flat ground needs no swing at all: the usable foot-rim arc runs
    #: out, and the leg then lifts off and repositions.  One nominal cycle is
    #: ``FOOT_RIM_ROLL + RECOVERY_SWING``; this member is only its first half,
    #: and a consumer that counts flat-ground swings as zero is reading a
    #: refuted claim.
    #:
    #: It is a *rename with a promotion*, not a new motion: Day 6--7's
    #: ``APPROACH`` segment already rolls the foot rim along flat ground at
    #: ``theta = 60 deg``.  What ``APPROACH`` cannot say is "this is what the
    #: robot does when there is no obstacle" -- its name asserts one.  Day 12
    #: needs the obstacle-free reading, so the two kinds stay separate and
    #: ``APPROACH`` keeps meaning "the run-up to a transition".
    FOOT_RIM_ROLL = "FOOT_RIM_ROLL"
    #: Day 12: the **airborne** half of the nominal Hybrid cycle.  When the
    #: rolling stroke reaches the end of the usable arc the leg lifts off,
    #: retracts toward a compact posture, carries on in the same forward
    #: rotation sense while airborne, and extends again into whatever the next
    #: touchdown contact requires.
    #:
    #: It is a swing, and it is deliberately **not** one of the three
    #: terrain-transition swings.  Day 12 plan §18 requires the metrics to
    #: report "nominal recovery swing count" and "terrain-transition swing
    #: count" separately, because the whole Hybrid-vs-Walk comparison turns on
    #: telling apart the swings the gait always makes from the ones the terrain
    #: forced.  Folding this into ``SWING_UP`` would destroy that distinction
    #: at the source.
    RECOVERY_SWING = "RECOVERY_SWING"
    #: Rolling on along whichever rim a swing just landed on, limited by the
    #: arc that remains before the rim runs out.
    POST_TOUCHDOWN_ROLL = "POST_TOUCHDOWN_ROLL"

    @property
    def is_swing(self) -> bool:
        """Airborne, whatever the reason.  See :attr:`is_terrain_transition`
        for the split that actually matters to the Day 12 metrics."""

        return self in (
            SegmentKind.SWING_UP, SegmentKind.SWING_DOWN, SegmentKind.SWING_OVER,
            SegmentKind.TOP_REPOSITION_SWING, SegmentKind.RECOVERY_SWING,
        )

    @property
    def is_rolling(self) -> bool:
        return not self.is_swing

    @property
    def pins_theta(self) -> bool:
        """Whether the kind's definition fixes ``theta`` to wheel mode.

        True for ``WHEEL_ROLL`` alone.  This is the machine-checkable half of
        the Day 12 freeze: without it, "FOOT_RIM_ROLL is not wheel mode" lives
        only in prose and a consumer is free to read the two as the same thing.
        """

        return self is SegmentKind.WHEEL_ROLL

    @property
    def is_nominal_locomotion(self) -> bool:
        """Whether the kind is part of the cycle the gait runs with no terrain
        feature in sight.

        Two members, because the Day 12 plan's FINAL FREEZE (§0.2) defines one
        nominal cycle as ``FOOT_RIM_ROLL + RECOVERY_SWING``.  Before that
        revision this property returned ``FOOT_RIM_ROLL`` alone, which encoded
        the since-retracted claim that flat ground needs no swing.

        ``APPROACH`` is deliberately not nominal: it is named for the obstacle
        it is approaching, and a nominal run happens where there is nothing to
        approach.
        """

        return self in (
            SegmentKind.FOOT_RIM_ROLL, SegmentKind.RECOVERY_SWING
        )

    @property
    def is_terrain_transition(self) -> bool:
        """Whether the terrain is what put this segment in the plan.

        The complement of :attr:`is_nominal_locomotion` over everything that is
        not plain wheel mode.  Day 12 plan §18 asks the metrics to count
        nominal recovery swings apart from terrain-transition swings; this is
        the predicate that does it, so the split lives in one place rather than
        being re-derived by each consumer from a list of names.
        """

        return not (self.is_nominal_locomotion or self is SegmentKind.WHEEL_ROLL)


class RollingMode(str, Enum):
    """Which coordinate is actually moving during a rolling segment.

    Measured distinction, not a taxonomy: Step 10R spends 72 of its 299 frames
    in ``CORNER_PIVOT``, where ``alpha`` and the contact point are both frozen.
    """

    #: The rim rolls over the terrain: ``alpha`` and the contact point move.
    SURFACE_ROLL = "surface roll"
    #: The leg rotates about one point on the rim: ``alpha`` and the contact
    #: point are pinned and ``beta`` sweeps.
    CORNER_PIVOT = "corner pivot"


